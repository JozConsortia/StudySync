-- StudySync database (MySQL 8+)
-- Users, plus each user's question history and saved answers.
-- Uploaded exam papers themselves are never stored.

CREATE DATABASE IF NOT EXISTS studysync
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE studysync;

CREATE TABLE IF NOT EXISTS users (
  id            INT UNSIGNED NOT NULL AUTO_INCREMENT,
  full_name     VARCHAR(100) NOT NULL,
  email         VARCHAR(255) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_users_email (email)
) ENGINE=InnoDB;

-- One row per scanned paper or typed question.
CREATE TABLE IF NOT EXISTS history_sessions (
  id          INT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id     INT UNSIGNED NOT NULL,
  client_id   VARCHAR(40)  NOT NULL,             -- id generated by the app, unique per user
  kind        ENUM('paper', 'typed') NOT NULL DEFAULT 'paper',
  title       VARCHAR(255) NOT NULL,
  subject     VARCHAR(100) NOT NULL DEFAULT '',
  file_name   VARCHAR(255) NULL,
  method      VARCHAR(20)  NULL,                 -- pdf-text, ocr, pdf-text+ocr, typed
  pages       SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_history_user_client (user_id, client_id),
  KEY ix_history_user_updated (user_id, updated_at),
  CONSTRAINT fk_history_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- The questions in a history session, with the AI solution once solved.
CREATE TABLE IF NOT EXISTS history_questions (
  id              INT UNSIGNED NOT NULL AUTO_INCREMENT,
  session_id      INT UNSIGNED NOT NULL,
  position        SMALLINT UNSIGNED NOT NULL,
  question_ref    VARCHAR(20)  NOT NULL,          -- the app's id for the question, e.g. q3
  question_number VARCHAR(20)  NOT NULL,          -- as printed on the paper, e.g. 1.2
  question_text   TEXT         NOT NULL,
  marks           DECIMAL(6,2) NULL,
  solved          BOOLEAN      NOT NULL DEFAULT FALSE,
  answer          TEXT         NULL,
  steps           JSON         NULL,              -- [{"title": ..., "detail": ...}]
  explanation     TEXT         NULL,
  tips            JSON         NULL,              -- ["...", "..."]
  followups       JSON         NULL,              -- [{"question": ..., "answer": ..., "askedAt": ...}]
  PRIMARY KEY (id),
  KEY ix_questions_session (session_id, position),
  CONSTRAINT fk_questions_session FOREIGN KEY (session_id) REFERENCES history_sessions (id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- One-time codes for "Forgot password". One active code per user, stored only as a hash.
CREATE TABLE IF NOT EXISTS password_resets (
  user_id     INT UNSIGNED NOT NULL,
  code_hash   CHAR(64)     NOT NULL,
  expires_at  DATETIME     NOT NULL,              -- UTC
  attempts    TINYINT UNSIGNED NOT NULL DEFAULT 0,
  created_at  DATETIME     NOT NULL,              -- UTC
  PRIMARY KEY (user_id),
  CONSTRAINT fk_resets_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- Each user's daily challenges: the questions (with their answers, never sent to the app before they are
-- answered), the student's results and the day's score.
CREATE TABLE IF NOT EXISTS daily_challenges (
  id            INT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id       INT UNSIGNED NOT NULL,
  day           DATE         NOT NULL,            -- the student's local date
  difficulty    VARCHAR(10)  NOT NULL,            -- easy, medium, hard
  items         JSON         NOT NULL,
  results       JSON         NULL,                -- {"c1": {"score": 10, ...}, ...}
  score         SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  max_score     SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  completed_at  TIMESTAMP    NULL,
  created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_challenge_user_day (user_id, day),
  CONSTRAINT fk_challenge_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- Answers a user bookmarked with "Save".
CREATE TABLE IF NOT EXISTS saved_answers (
  id              INT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id         INT UNSIGNED NOT NULL,
  saved_key       VARCHAR(400) NOT NULL,          -- identifies the question so it is saved once
  paper_title     VARCHAR(255) NOT NULL,
  subject         VARCHAR(100) NOT NULL DEFAULT '',
  question_number VARCHAR(20)  NOT NULL,
  question_text   TEXT         NOT NULL,
  marks           DECIMAL(6,2) NULL,
  answer          TEXT         NOT NULL,
  steps           JSON         NOT NULL,
  explanation     TEXT         NOT NULL,
  tips            JSON         NOT NULL,
  followups       JSON         NULL,              -- follow-up questions and replies, as in history_questions
  saved_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_saved_user_key (user_id, saved_key),
  KEY ix_saved_user_date (user_id, saved_at),
  CONSTRAINT fk_saved_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
) ENGINE=InnoDB;
