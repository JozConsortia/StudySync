import { jsPDF } from "jspdf";

const MARGIN = 48;

// Renders questions and their solutions into a downloadable PDF.
// items: [{ number, text, marks, solution: { answer, steps, explanation, tips } }]
export function downloadPdf({ title, subject, items, fileName }) {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const pageW = doc.internal.pageSize.getWidth();
  const pageH = doc.internal.pageSize.getHeight();
  const width = pageW - MARGIN * 2;
  let y = MARGIN;

  const ensure = (h) => {
    if (y + h > pageH - MARGIN) {
      doc.addPage();
      y = MARGIN;
    }
  };

  const write = (text, { size = 11, style = "normal", color = [20, 20, 20], gap = 4, indent = 0 } = {}) => {
    doc.setFont("helvetica", style);
    doc.setFontSize(size);
    doc.setTextColor(...color);
    const lines = doc.splitTextToSize(String(text || ""), width - indent);
    const lh = size * 1.35;
    for (const line of lines) {
      ensure(lh);
      doc.text(line, MARGIN + indent, y + size);
      y += lh;
    }
    y += gap;
  };

  write(title || "StudySync answers", { size: 20, style: "bold", gap: 2 });
  write([subject, `Generated by StudySync on ${new Date().toLocaleDateString()}`].filter(Boolean).join("  ·  "), {
    size: 10,
    color: [110, 110, 110],
    gap: 16,
  });

  items.forEach((q, idx) => {
    if (idx > 0) {
      ensure(24);
      doc.setDrawColor(220);
      doc.line(MARGIN, y, pageW - MARGIN, y);
      y += 16;
    }
    write(`Question ${q.number}${q.marks ? ` (${q.marks} marks)` : ""}`, { size: 13, style: "bold", gap: 4 });
    write(q.text, { gap: 10 });

    const s = q.solution;
    if (!s) {
      write("Not solved yet.", { style: "italic", color: [130, 130, 130], gap: 8 });
      return;
    }
    write("Answer", { size: 11, style: "bold", color: [40, 90, 220], gap: 2 });
    write(s.answer, { gap: 10 });

    if (s.steps?.length) {
      write("Step-by-step solution", { size: 11, style: "bold", color: [40, 90, 220], gap: 2 });
      s.steps.forEach((step, i) => {
        write(`${i + 1}. ${step.title}`, { style: "bold", gap: 1, indent: 8 });
        write(step.detail, { gap: 6, indent: 22 });
      });
      y += 4;
    }
    if (s.explanation) {
      write("Explanation", { size: 11, style: "bold", color: [40, 90, 220], gap: 2 });
      write(s.explanation, { gap: 10 });
    }
    if (s.tips?.length) {
      write("Exam tips", { size: 11, style: "bold", color: [40, 90, 220], gap: 2 });
      s.tips.forEach((t) => write(`•  ${t}`, { gap: 2, indent: 8 }));
      y += 8;
    }
  });

  doc.save(fileName || `${(title || "studysync").replace(/[^\w\- ]+/g, "").trim() || "studysync"}.pdf`);
}
