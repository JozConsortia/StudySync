import { jsPDF } from "jspdf";
import { languageLabel, parseRichText, splitComment } from "./richtext.js";

const MARGIN = 48;

// Renders questions and their solutions into a downloadable PDF.
// items: [{ number, text, marks, solution: { answer, steps, explanation, tips }, followups?: [{ question, answer }] }]
export function downloadPdf({ title, subject, items, fileName }) {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const pageW = doc.internal.pageSize.getWidth();
  const pageH = doc.internal.pageSize.getHeight();
  const width = pageW - MARGIN * 2;
  let y = MARGIN;

  const ensure = (h) => {
    if (y + h > pageH - MARGIN) {
      doc.addPage();
      y = MARGIN;
    }
  };

  const write = (text, { size = 11, style = "normal", color = [20, 20, 20], gap = 4, indent = 0 } = {}) => {
    doc.setFont("helvetica", style);
    doc.setFontSize(size);
    doc.setTextColor(...color);
    const lines = doc.splitTextToSize(String(text || ""), width - indent);
    const lh = size * 1.35;
    for (const line of lines) {
      ensure(lh);
      doc.text(line, MARGIN + indent, y + size);
      y += lh;
    }
    y += gap;
  };

  // Code: monospace on a light grey background, indentation kept. Long lines wrap and the continuation
  // keeps the line's indentation so the structure stays readable.
  const writeCode = (code, lang, { indent = 0, gap = 8 } = {}) => {
    const size = 9;
    const lh = size * 1.45;
    const x = MARGIN + indent;
    const boxW = width - indent;
    doc.setFont("courier", "normal");
    doc.setFontSize(size);
    const charW = doc.getTextWidth("M");
    const maxChars = Math.max(20, Math.floor((boxW - 16) / charW));

    const rows = [];
    for (const line of code.split("\n")) {
      const lead = line.length - line.trimStart().length;
      let rest = line.trimStart();
      const room = Math.max(10, maxChars - lead);
      if (!rest) rows.push("");
      while (rest) {
        rows.push(" ".repeat(Math.min(lead, maxChars - 10)) + rest.slice(0, room));
        rest = rest.slice(room);
      }
    }

    ensure(lh * 2 + 10);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(8);
    doc.setTextColor(110, 110, 120);
    doc.text(languageLabel(lang).toUpperCase(), x, y + 8);
    y += 12;
    for (const row of rows) {
      ensure(lh);
      doc.setFillColor(244, 245, 248);
      doc.rect(x, y, boxW, lh, "F");
      doc.setFont("courier", "normal");
      doc.setFontSize(size);
      const [src, comment] = splitComment(row, lang);
      doc.setTextColor(25, 25, 30);
      doc.text(src, x + 8, y + size + 1);
      if (comment) {
        doc.setTextColor(46, 125, 70);
        doc.text(comment, x + 8 + doc.getTextWidth(src), y + size + 1);
      }
      y += lh;
    }
    y += gap;
  };

  // Text that may contain code blocks.
  const writeRich = (text, { gap = 4, indent = 0, ...opts } = {}) => {
    const parts = parseRichText(text);
    if (!parts.length) return;
    parts.forEach((p, i) => {
      const last = i === parts.length - 1;
      if (p.type === "code") writeCode(p.content, p.lang, { indent, gap: last ? gap : 6 });
      else write(p.content, { ...opts, indent, gap: last ? gap : 4 });
    });
  };

  write(title || "StudySync answers", { size: 20, style: "bold", gap: 2 });
  write([subject, `Generated by StudySync on ${new Date().toLocaleDateString()}`].filter(Boolean).join("  ·  "), {
    size: 10,
    color: [110, 110, 110],
    gap: 16,
  });

  items.forEach((q, idx) => {
    if (idx > 0) {
      ensure(24);
      doc.setDrawColor(220);
      doc.line(MARGIN, y, pageW - MARGIN, y);
      y += 16;
    }
    write(`Question ${q.number}${q.marks ? ` (${q.marks} marks)` : ""}`, { size: 13, style: "bold", gap: 4 });
    writeRich(q.text, { gap: 10 });

    const s = q.solution;
    if (!s) {
      write("Not solved yet.", { style: "italic", color: [130, 130, 130], gap: 8 });
      return;
    }
    write("Answer", { size: 11, style: "bold", color: [40, 90, 220], gap: 2 });
    writeRich(s.answer, { gap: 10 });

    if (s.steps?.length) {
      write("Step-by-step solution", { size: 11, style: "bold", color: [40, 90, 220], gap: 2 });
      s.steps.forEach((step, i) => {
        write(`${i + 1}. ${step.title}`, { style: "bold", gap: 1, indent: 8 });
        writeRich(step.detail, { gap: 6, indent: 22 });
      });
      y += 4;
    }
    if (s.explanation) {
      write("Explanation", { size: 11, style: "bold", color: [40, 90, 220], gap: 2 });
      writeRich(s.explanation, { gap: 10 });
    }
    if (s.tips?.length) {
      write("Exam tips", { size: 11, style: "bold", color: [40, 90, 220], gap: 2 });
      s.tips.forEach((t) => write(`•  ${t}`, { gap: 2, indent: 8 }));
      y += 8;
    }
    if (q.followups?.length) {
      write("Follow-up questions", { size: 11, style: "bold", color: [40, 90, 220], gap: 4 });
      q.followups.forEach((f) => {
        write(`You: ${f.question}`, { style: "bold", gap: 2, indent: 8 });
        writeRich(f.answer, { gap: 8, indent: 22 });
      });
    }
  });

  doc.save(fileName || `${(title || "studysync").replace(/[^\w\- ]+/g, "").trim() || "studysync"}.pdf`);
}
