import * as Print from 'expo-print';
import * as Sharing from 'expo-sharing';
import { languageLabel, parseRichText, splitComment } from './richtext';

const escCode = (s) => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const esc = (s) =>
  String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/\n/g, '<br/>');

// Text with code blocks: code keeps its indentation in a monospace box, comments in green.
function rich(text) {
  return parseRichText(text)
    .map((p) => {
      if (p.type === 'text') return `<p>${esc(p.content)}</p>`;
      const lines = p.content.split('\n').map((line) => {
        const [src, comment] = splitComment(line, p.lang);
        return escCode(src) + (comment ? `<span class="cm">${escCode(comment)}</span>` : '');
      });
      return `<div class="code"><div class="lang">${esc(languageLabel(p.lang))}</div><pre>${lines.join('\n')}</pre></div>`;
    })
    .join('');
}

function questionHtml(q) {
  const s = q.solution;
  const head = `<h2>Question ${esc(q.number)}${q.marks ? ` <span class="marks">(${q.marks} marks)</span>` : ''}</h2>
    ${rich(q.text)}`;
  if (!s) return `<section>${head}<p class="muted">Not solved yet.</p></section>`;

  const steps = s.steps?.length
    ? `<h3>Step-by-step solution</h3><ol>${s.steps
        .map((st) => `<li><strong>${esc(st.title)}</strong>${rich(st.detail)}</li>`)
        .join('')}</ol>`
    : '';
  const tips = s.tips?.length ? `<h3>Exam tips</h3><ul>${s.tips.map((t) => `<li>${rich(t)}</li>`).join('')}</ul>` : '';

  return `<section>${head}
    <h3>Answer</h3><div class="answer">${rich(s.answer)}</div>
    ${steps}
    ${s.explanation ? `<h3>Explanation</h3>${rich(s.explanation)}` : ''}
    ${tips}</section>`;
}

// Builds a PDF of the given questions/solutions and opens the share sheet to save or send it.
export async function sharePdf({ title, subject, items }) {
  const html = `<!doctype html><html><head><meta charset="utf-8"/>
  <style>
    body { font-family: -apple-system, Roboto, Helvetica, sans-serif; color: #141414; padding: 28px; font-size: 13px; line-height: 1.5; }
    h1 { font-size: 22px; margin: 0 0 4px; }
    h2 { font-size: 16px; margin: 0 0 6px; }
    h3 { font-size: 12px; text-transform: uppercase; letter-spacing: .05em; color: #2856dc; margin: 14px 0 4px; }
    .muted, .marks { color: #777; font-weight: normal; }
    .answer { font-weight: 600; }
    section { border-top: 1px solid #ddd; padding-top: 16px; margin-top: 16px; page-break-inside: avoid; }
    li { margin-bottom: 6px; }
    p { margin: 4px 0; }
    .answer p { font-weight: 600; }
    .answer .code pre { font-weight: 400; }
    .code { margin: 6px 0 10px; border: 1px solid #dcdde3; border-radius: 6px; background: #f4f5f8; page-break-inside: avoid; }
    .code .lang { padding: 4px 10px; border-bottom: 1px solid #dcdde3; font-size: 10px; font-weight: 700; color: #6e6e78; text-transform: uppercase; }
    .code pre { margin: 0; padding: 8px 10px; font-family: Menlo, Consolas, 'Courier New', monospace; font-size: 11px; line-height: 1.5; white-space: pre-wrap; tab-size: 4; }
    .cm { color: #2e7d46; font-style: italic; }
  </style></head><body>
  <h1>${esc(title || 'StudySync answers')}</h1>
  <p class="muted">${[subject, `Generated by StudySync on ${new Date().toLocaleDateString()}`].filter(Boolean).map(esc).join(' · ')}</p>
  ${items.map(questionHtml).join('')}
  </body></html>`;

  const { uri } = await Print.printToFileAsync({ html });
  if (await Sharing.isAvailableAsync()) {
    await Sharing.shareAsync(uri, { mimeType: 'application/pdf', UTI: 'com.adobe.pdf', dialogTitle: title });
  } else {
    await Print.printAsync({ uri });
  }
}
