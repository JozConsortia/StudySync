import * as Print from 'expo-print';
import * as Sharing from 'expo-sharing';

const esc = (s) =>
  String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/\n/g, '<br/>');

function questionHtml(q) {
  const s = q.solution;
  const head = `<h2>Question ${esc(q.number)}${q.marks ? ` <span class="marks">(${q.marks} marks)</span>` : ''}</h2>
    <p>${esc(q.text)}</p>`;
  if (!s) return `<section>${head}<p class="muted">Not solved yet.</p></section>`;

  const steps = s.steps?.length
    ? `<h3>Step-by-step solution</h3><ol>${s.steps
        .map((st) => `<li><strong>${esc(st.title)}</strong><br/>${esc(st.detail)}</li>`)
        .join('')}</ol>`
    : '';
  const tips = s.tips?.length ? `<h3>Exam tips</h3><ul>${s.tips.map((t) => `<li>${esc(t)}</li>`).join('')}</ul>` : '';

  return `<section>${head}
    <h3>Answer</h3><p class="answer">${esc(s.answer)}</p>
    ${steps}
    ${s.explanation ? `<h3>Explanation</h3><p>${esc(s.explanation)}</p>` : ''}
    ${tips}</section>`;
}

// Builds a PDF of the given questions/solutions and opens the share sheet to save or send it.
export async function sharePdf({ title, subject, items }) {
  const html = `<!doctype html><html><head><meta charset="utf-8"/>
  <style>
    body { font-family: -apple-system, Roboto, Helvetica, sans-serif; color: #141414; padding: 28px; font-size: 13px; line-height: 1.5; }
    h1 { font-size: 22px; margin: 0 0 4px; }
    h2 { font-size: 16px; margin: 0 0 6px; }
    h3 { font-size: 12px; text-transform: uppercase; letter-spacing: .05em; color: #2856dc; margin: 14px 0 4px; }
    .muted, .marks { color: #777; font-weight: normal; }
    .answer { font-weight: 600; }
    section { border-top: 1px solid #ddd; padding-top: 16px; margin-top: 16px; page-break-inside: avoid; }
    li { margin-bottom: 6px; }
  </style></head><body>
  <h1>${esc(title || 'StudySync answers')}</h1>
  <p class="muted">${[subject, `Generated by StudySync on ${new Date().toLocaleDateString()}`].filter(Boolean).map(esc).join(' · ')}</p>
  ${items.map(questionHtml).join('')}
  </body></html>`;

  const { uri } = await Print.printToFileAsync({ html });
  if (await Sharing.isAvailableAsync()) {
    await Sharing.shareAsync(uri, { mimeType: 'application/pdf', UTI: 'com.adobe.pdf', dialogTitle: title });
  } else {
    await Print.printAsync({ uri });
  }
}
