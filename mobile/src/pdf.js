import { Alert, Platform } from 'react-native';
import * as Print from 'expo-print';
import * as Sharing from 'expo-sharing';
import * as FileSystem from 'expo-file-system/legacy';
import AsyncStorage from '@react-native-async-storage/async-storage';
import { languageLabel, parseRichText, splitComment } from './richtext';

const escCode = (s) => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const esc = (s) =>
  String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/\n/g, '<br/>');

// Text with code blocks: code keeps its indentation in a monospace box, comments in green.
function rich(text) {
  return parseRichText(text)
    .map((p) => {
      if (p.type === 'text') return `<p>${esc(p.content)}</p>`;
      const lines = p.content.split('\n').map((line) => {
        const [src, comment] = splitComment(line, p.lang);
        return escCode(src) + (comment ? `<span class="cm">${escCode(comment)}</span>` : '');
      });
      return `<div class="code"><div class="lang">${esc(languageLabel(p.lang))}</div><pre>${lines.join('\n')}</pre></div>`;
    })
    .join('');
}

function questionHtml(q) {
  const s = q.solution;
  const head = `<h2>Question ${esc(q.number)}${q.marks ? ` <span class="marks">(${q.marks} marks)</span>` : ''}</h2>
    ${rich(q.text)}`;
  if (!s) return `<section>${head}<p class="muted">Not solved yet.</p></section>`;

  const steps = s.steps?.length
    ? `<h3>Step-by-step solution</h3><ol>${s.steps
        .map((st) => `<li><strong>${esc(st.title)}</strong>${rich(st.detail)}</li>`)
        .join('')}</ol>`
    : '';
  const tips = s.tips?.length ? `<h3>Exam tips</h3><ul>${s.tips.map((t) => `<li>${rich(t)}</li>`).join('')}</ul>` : '';
  const followups = q.followups?.length
    ? `<h3>Follow-up questions</h3>${q.followups
        .map((f) => `<div class="fu"><p class="fu-q">You: ${esc(f.question)}</p>${rich(f.answer)}</div>`)
        .join('')}`
    : '';

  return `<section>${head}
    <h3>Answer</h3><div class="answer">${rich(s.answer)}</div>
    ${steps}
    ${s.explanation ? `<h3>Explanation</h3>${rich(s.explanation)}` : ''}
    ${tips}
    ${followups}</section>`;
}

